const norm = (s) => String(s || '').toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я0-9{}!/#@ -]/g, ' ').replace(/\s+/g, ' ').trim();

// Ответ на вопрос: { kind: 'topic'|'check'|'unknown', title, lines, go, more }
export function answer(question, ctx) {
  const q = norm(question);
  if (!q) return unknown();
  if (/(проверь|проверить|чего не хват|что не настроен|что осталос|что еще|что ещё|готов ли)/.test(q) || q === 'проверить мою настройку') return checkSetup(ctx);
  let best = null;
  let bestScore = 0;
  for (const t of TOPICS) {
    let score = 0;
    for (const k of t.keys) {
      const key = norm(k);
      if (key && (` ${q}`).includes(` ${key}`)) score += key.length >= 6 ? 3 : 2;   // совпадение с начала слова
    }
    if (score > bestScore) { best = t; bestScore = score; }
  }
  if (!best) return unknown();
  return { kind: 'topic', title: best.title, lines: best.lines, go: best.go, more: best.more };
}

function unknown() {
  return {
    kind: 'unknown',
    title: 'Не нашёл такой подсказки',
    lines: ['Я простой помощник по готовым подсказкам и могу ответить на вопросы про кабинет и команды бота. Попробуйте спросить иначе или выберите тему ниже.'],
    go: [],
    more: QUICK,
  };
}

// Что в кабинете ещё не настроено. ctx: { ch, predLink, isOwn }
export function checkSetup(ctx) {
  if (!ctx || !ctx.ch) {
    return { kind: 'check', title: 'Проверка настройки', lines: ['Кабинет канала ещё не загружен. Откройте его и спросите снова.'], go: [], more: [] };
  }
  const { ch } = ctx;
  const items = [];
  const add = (ok, good, bad, panel, label) => items.push({ ok, text: ok ? good : bad, panel: ok ? null : panel, label });
  add(ch.enabled, 'Бот на канале включён.', 'Бот на канале выключен: он не отвечает в чате. Включите переключатель на обзоре.', 'overview', 'Обзор');
  add(!!(ch.name && ch.tag), `Аккаунт Valorant задан (${ch.name}#${ch.tag}).`, 'Не задан аккаунт Valorant: !rank не будет работать.', 'valorant', 'Valorant');
  add(ch.commands.length > 0, `Свои команды есть (${ch.commands.length}).`, 'Нет своих команд. Добавьте хотя бы !discord или !social.', 'commands', 'Команды');
  add(ch.timers.length > 0 && !ch.timerOff, `Авто-сообщения работают (${ch.timers.length}).`, ch.timers.length ? 'Авто-сообщения добавлены, но выключены.' : 'Нет авто-сообщений (необязательно).', 'timers', 'Авто-сообщения');
  add(ch.filters.on, 'Фильтры чата включены.', 'Фильтры чата выключены (необязательно, но помогают от спама и ссылок).', 'filters', 'Фильтры');
  add(ch.points.on, 'Очки включены.', 'Очки выключены (необязательно: нужны для магазина и ставок в играх).', 'points', 'Очки');
  add(ch.games, 'Мини-игры включены.', 'Мини-игры выключены (необязательно).', 'games', 'Игры');
  add(ctx.predLink === true, 'Предсказания Twitch подключены.',
    ctx.predLink === undefined ? 'Состояние предсказаний ещё загружается.' : ctx.isOwn === false ? 'Предсказания Twitch не подключены: подключить может только владелец канала.' : 'Предсказания Twitch не подключены (необязательно). Нужен статус партнёра или компаньона.', 'pred', 'Предсказания');
  const todo = items.filter((i) => !i.ok);
  const lines = items.map((i) => `${i.ok ? '✓' : '•'} ${i.text}`);
  lines.push('Этот список проверяет только то, что видно в кабинете. Выдан ли боту модератор в вашем чате (/mod имя_бота), отсюда увидеть нельзя.');
  const seen = new Set();
  const go = [];
  for (const i of todo) if (i.panel && !seen.has(i.panel)) { seen.add(i.panel); go.push({ label: i.label, panel: i.panel }); }
  return { kind: 'check', title: todo.length ? 'Проверка настройки: есть что доделать' : 'Проверка настройки: всё настроено', lines, go: go.slice(0, 4), more: [] };
}
