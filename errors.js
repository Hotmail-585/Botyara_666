// «Сервер не принял изменение. E301»: короткий текст и код через пробел (добавочные данные в скобках).
export function errText(code, extra) {
  return `${ERR[code] || 'Ошибка.'} ${code}${extra ? ` (${extra})` : ''}`;
}
